#!/usr/bin/env bash
# MedTrustX Device Trust Agent — macOS Build Script
#
# Builds a self-contained macOS app bundle / universal binary using PyInstaller,
# then codesigns and notarizes it via Apple's notarytool.
#
# Prerequisites:
#   - Python 3.11+ (brew install python@3.11 recommended)
#   - Xcode Command Line Tools (xcode-select --install)
#   - Apple Developer ID Application certificate in Keychain
#   - App Store Connect API key for notarytool (or Apple ID credentials)
#
# Environment variables:
#   SIGN_IDENTITY          — Developer ID Application: Your Name (TEAMID)
#   NOTARIZE_KEYCHAIN_PROFILE — keychain profile created via:
#                              xcrun notarytool store-credentials
#   NOTARIZE_APPLE_ID      — Apple ID email (alternative to keychain profile)
#   NOTARIZE_TEAM_ID       — Apple Developer Team ID
#   NOTARIZE_APP_PASSWORD  — App-specific password for notarization
#   BUILD_VERSION          — version string (default: read from pyproject.toml)
#   DIST_DIR               — output directory (default: dist)
#   SKIP_SIGN              — set to 1 to skip codesign + notarize
#   SKIP_NOTARIZE          — set to 1 to skip notarize only (sign still runs)
#   ARCH                   — x86_64 | arm64 | universal2 (default: universal2)
#
# Usage:
#   ./build/build_macos.sh
#   SKIP_SIGN=1 ./build/build_macos.sh
#   ARCH=arm64 BUILD_VERSION=1.2.0 ./build/build_macos.sh

set -euo pipefail

# ── Configuration ─────────────────────────────────────────────────────────────

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
AGENT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
DIST_DIR="${DIST_DIR:-$AGENT_ROOT/dist}"
WORK_DIR="$SCRIPT_DIR/pyinstaller_work_macos"
EXE_NAME="medtrustx-agent"
EXE_PATH="$DIST_DIR/$EXE_NAME"
ARCH="${ARCH:-universal2}"
BUILD_VERSION="${BUILD_VERSION:-}"
SKIP_SIGN="${SKIP_SIGN:-0}"
SKIP_NOTARIZE="${SKIP_NOTARIZE:-0}"
SIGN_IDENTITY="${SIGN_IDENTITY:-}"
NOTARIZE_KEYCHAIN_PROFILE="${NOTARIZE_KEYCHAIN_PROFILE:-}"
NOTARIZE_APPLE_ID="${NOTARIZE_APPLE_ID:-}"
NOTARIZE_TEAM_ID="${NOTARIZE_TEAM_ID:-}"
NOTARIZE_APP_PASSWORD="${NOTARIZE_APP_PASSWORD:-}"

# ── Helpers ───────────────────────────────────────────────────────────────────

cyan()  { printf '\033[1;36m%s\033[0m\n' "$*"; }
green() { printf '\033[1;32m[OK] %s\033[0m\n' "$*"; }
warn()  { printf '\033[1;33m[WARN] %s\033[0m\n' "$*" >&2; }
die()   { printf '\033[1;31m[FAIL] %s\033[0m\n' "$*" >&2; exit 1; }

step() { echo; cyan "[MedTrustX Build] $*"; }

# ── Verify environment ────────────────────────────────────────────────────────

step "Verifying build environment"

python3 --version | grep -qE "Python 3\.(1[1-9]|[2-9][0-9])" \
    || die "Python 3.11+ required"
echo "  Python: $(python3 --version)"

if [[ "$ARCH" == "universal2" ]]; then
    # Need both architectures available
    if ! python3 -c "import platform; assert platform.machine() in ('arm64','x86_64')" 2>/dev/null; then
        warn "Universal2 build may fail on this host; set ARCH=arm64 or ARCH=x86_64"
    fi
fi

# ── Read version from pyproject.toml if not set ───────────────────────────────

if [[ -z "$BUILD_VERSION" ]]; then
    if command -v python3 &>/dev/null; then
        BUILD_VERSION=$(python3 - <<'PY'
import re, pathlib
text = pathlib.Path("pyproject.toml").read_text()
m = re.search(r'^version\s*=\s*"([^"]+)"', text, re.MULTILINE)
print(m.group(1) if m else "1.0.0")
PY
        ) || BUILD_VERSION="1.0.0"
    else
        BUILD_VERSION="1.0.0"
    fi
fi
echo "  Build version: $BUILD_VERSION"

# ── Install PyInstaller if needed ─────────────────────────────────────────────

step "Checking PyInstaller"
if ! python3 -m PyInstaller --version &>/dev/null; then
    echo "  Installing PyInstaller…"
    python3 -m pip install pyinstaller
fi
echo "  PyInstaller: $(python3 -m PyInstaller --version)"

# ── Write PyInstaller spec ────────────────────────────────────────────────────

step "Writing PyInstaller spec"
SPEC_FILE="$SCRIPT_DIR/medtrustx_agent_macos.spec"

cat > "$SPEC_FILE" <<SPEC
# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by build_macos.sh

block_cipher = None
import sys
from pathlib import Path

agent_root = Path(r'${AGENT_ROOT}')

a = Analysis(
    [str(agent_root / 'src' / 'main.py')],
    pathex=[str(agent_root)],
    binaries=[],
    datas=[(str(agent_root / '.env.example'), '.')],
    hiddenimports=[
        'src.checks.check_01_os_patch',
        'src.checks.check_02_antivirus',
        'src.checks.check_03_disk_encryption',
        'src.checks.check_04_firewall',
        'src.checks.check_05_screen_lock',
        'src.checks.check_06_jailbreak',
        'src.checks.check_07_certificate',
        'src.checks.check_08_network',
        'src.checks.check_09_processes',
        'src.checks.check_10_behavioral',
        'src.daemon.linux_daemon',
        'src.daemon.macos_daemon',
        'src.daemon.windows_service',
        'src.reporting.zta_reporter',
        'src.reporting.siem_reporter',
        'src.reporting.prometheus_reporter',
        'src.reporting.opa_reporter',
        'cryptography.hazmat.backends.openssl',
        'cryptography.hazmat.primitives.asymmetric.padding',
        'cryptography.x509.ocsp',
        'psycopg2',
        'psycopg2.extensions',
        'aiohttp',
        'aiohttp.web',
        'netifaces',
        'psutil',
        'structlog',
        'click',
        'pydantic',
        'pydantic_settings',
    ],
    hookspath=[],
    hooksconfig={},
    runtime_hooks=[],
    excludes=['tkinter', 'matplotlib', 'numpy', 'scipy', 'PIL'],
    win_no_prefer_redirects=False,
    win_private_assemblies=False,
    cipher=block_cipher,
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)

exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.zipfiles,
    a.datas,
    [],
    name='${EXE_NAME}',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=False,
    upx_exclude=[],
    runtime_tmpdir=None,
    console=True,
    disable_windowed_traceback=False,
    target_arch='${ARCH}',
    codesign_identity=None,
    entitlements_file=None,
)
SPEC

echo "  Wrote: $SPEC_FILE"

# ── Run PyInstaller ───────────────────────────────────────────────────────────

step "Running PyInstaller (arch=$ARCH)"
cd "$AGENT_ROOT"
python3 -m PyInstaller \
    --clean \
    --noconfirm \
    --distpath "$DIST_DIR" \
    --workpath "$WORK_DIR" \
    --log-level WARN \
    "$SPEC_FILE"
green "PyInstaller build complete: $EXE_PATH"

# ── Code signing ──────────────────────────────────────────────────────────────

if [[ "$SKIP_SIGN" == "1" ]]; then
    warn "Skipping codesign (SKIP_SIGN=1)"
else
    step "Code-signing binary"
    if [[ -z "$SIGN_IDENTITY" ]]; then
        warn "SIGN_IDENTITY not set — skipping codesign"
    else
        # Write entitlements plist
        ENTITLEMENTS_FILE="$SCRIPT_DIR/medtrustx.entitlements"
        cat > "$ENTITLEMENTS_FILE" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <!-- Allow outbound network connections -->
    <key>com.apple.security.network.client</key>
    <true/>
    <!-- Allow reading system keychain for device certificate -->
    <key>com.apple.security.keychain-access-groups</key>
    <array>
        <string>com.medtrustx.agent</string>
    </array>
    <!-- Hardened runtime — required for notarization -->
    <key>com.apple.security.cs.allow-unsigned-executable-memory</key>
    <false/>
    <key>com.apple.security.cs.disable-library-validation</key>
    <false/>
</dict>
</plist>
PLIST

        codesign \
            --sign "$SIGN_IDENTITY" \
            --timestamp \
            --options runtime \
            --entitlements "$ENTITLEMENTS_FILE" \
            --force \
            "$EXE_PATH"
        green "Signed: $EXE_PATH"

        # Verify
        codesign --verify --deep --strict --verbose=2 "$EXE_PATH"
        green "Signature verified"

        spctl --assess --type execute --verbose "$EXE_PATH" \
            && green "Gatekeeper assessment passed" \
            || warn "Gatekeeper assessment failed (pre-notarization expected)"

        # ── Notarization ──────────────────────────────────────────────────────

        if [[ "$SKIP_NOTARIZE" == "1" ]]; then
            warn "Skipping notarization (SKIP_NOTARIZE=1)"
        else
            step "Notarizing binary"
            # Zip for submission
            NOTARIZE_ZIP="$DIST_DIR/${EXE_NAME}-notarize.zip"
            ditto -c -k --keepParent "$EXE_PATH" "$NOTARIZE_ZIP"

            if [[ -n "$NOTARIZE_KEYCHAIN_PROFILE" ]]; then
                xcrun notarytool submit "$NOTARIZE_ZIP" \
                    --keychain-profile "$NOTARIZE_KEYCHAIN_PROFILE" \
                    --wait \
                    --timeout 600
            elif [[ -n "$NOTARIZE_APPLE_ID" && -n "$NOTARIZE_TEAM_ID" && -n "$NOTARIZE_APP_PASSWORD" ]]; then
                xcrun notarytool submit "$NOTARIZE_ZIP" \
                    --apple-id "$NOTARIZE_APPLE_ID" \
                    --team-id  "$NOTARIZE_TEAM_ID" \
                    --password "$NOTARIZE_APP_PASSWORD" \
                    --wait \
                    --timeout 600
            else
                warn "No notarization credentials provided — skipping notarize"
                warn "Set NOTARIZE_KEYCHAIN_PROFILE or NOTARIZE_APPLE_ID+NOTARIZE_TEAM_ID+NOTARIZE_APP_PASSWORD"
            fi

            rm -f "$NOTARIZE_ZIP"

            # Staple notarization ticket
            xcrun stapler staple "$EXE_PATH" \
                && green "Notarization ticket stapled" \
                || warn "Staple failed — may still work online"

            spctl --assess --type execute --verbose "$EXE_PATH" \
                && green "Post-notarization Gatekeeper check passed" \
                || warn "Post-notarization Gatekeeper check failed"
        fi
    fi
fi

# ── Done ──────────────────────────────────────────────────────────────────────

EXE_SIZE=$(du -sh "$EXE_PATH" | awk '{print $1}')
echo
cyan "════════════════════════════════════════════════"
green "Build complete!"
echo "  Output : $EXE_PATH"
echo "  Size   : $EXE_SIZE"
echo "  Version: $BUILD_VERSION"
echo "  Arch   : $ARCH"
cyan "════════════════════════════════════════════════"
