#!/usr/bin/env bash
# MedTrustX Device Trust Agent — Linux Build Script
#
# Builds a self-contained Linux binary using PyInstaller, then packages it as
# both a .deb (Debian/Ubuntu) and .rpm (RHEL/CentOS/Fedora) archive.
#
# Prerequisites:
#   - Python 3.11+ in PATH
#   - pip install pyinstaller (included in requirements-dev.txt)
#   - dpkg-deb (apt-get install dpkg) — for .deb packaging
#   - rpmbuild (yum install rpm-build) — for .rpm packaging
#     (either packager is optional; only available ones are used)
#
# Environment variables:
#   BUILD_VERSION   — version string (default: from pyproject.toml)
#   DIST_DIR        — output directory (default: dist)
#   PACKAGE_DIR     — working directory for packaging (default: build/pkg_work)
#   SKIP_DEB        — set to 1 to skip .deb creation
#   SKIP_RPM        — set to 1 to skip .rpm creation
#   TARGET_ARCH     — x86_64 | aarch64 (default: detected from uname -m)
#
# Output (in $DIST_DIR):
#   medtrustx-agent              — standalone ELF binary
#   medtrustx-agent_<ver>_amd64.deb
#   medtrustx-agent-<ver>-1.x86_64.rpm

set -euo pipefail

# ── Configuration ─────────────────────────────────────────────────────────────

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
AGENT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
DIST_DIR="${DIST_DIR:-$AGENT_ROOT/dist}"
WORK_DIR="${PACKAGE_DIR:-$SCRIPT_DIR/pyinstaller_work_linux}"
PKG_WORK_DIR="$SCRIPT_DIR/pkg_work"
EXE_NAME="medtrustx-agent"
EXE_PATH="$DIST_DIR/$EXE_NAME"
BUILD_VERSION="${BUILD_VERSION:-}"
SKIP_DEB="${SKIP_DEB:-0}"
SKIP_RPM="${SKIP_RPM:-0}"
TARGET_ARCH="${TARGET_ARCH:-$(uname -m)}"

# Normalise arch names
case "$TARGET_ARCH" in
    x86_64)   DEB_ARCH="amd64"; RPM_ARCH="x86_64" ;;
    aarch64)  DEB_ARCH="arm64"; RPM_ARCH="aarch64" ;;
    arm64)    DEB_ARCH="arm64"; RPM_ARCH="aarch64" ;;
    *)        DEB_ARCH="$TARGET_ARCH"; RPM_ARCH="$TARGET_ARCH" ;;
esac

# ── Helpers ───────────────────────────────────────────────────────────────────

cyan()  { printf '\033[1;36m%s\033[0m\n' "$*"; }
green() { printf '\033[1;32m[OK] %s\033[0m\n' "$*"; }
warn()  { printf '\033[1;33m[WARN] %s\033[0m\n' "$*" >&2; }
die()   { printf '\033[1;31m[FAIL] %s\033[0m\n' "$*" >&2; exit 1; }
step()  { echo; cyan "[MedTrustX Build] $*"; }

# ── Verify environment ────────────────────────────────────────────────────────

step "Verifying build environment"
python3 --version | grep -qE "Python 3\.(1[1-9]|[2-9][0-9])" \
    || die "Python 3.11+ required"
echo "  Python  : $(python3 --version)"
echo "  Arch    : $TARGET_ARCH (deb=$DEB_ARCH, rpm=$RPM_ARCH)"

# ── Read version from pyproject.toml if not set ───────────────────────────────

if [[ -z "$BUILD_VERSION" ]]; then
    BUILD_VERSION=$(python3 - <<'PY'
import re, pathlib
text = pathlib.Path("pyproject.toml").read_text()
m = re.search(r'^version\s*=\s*"([^"]+)"', text, re.MULTILINE)
print(m.group(1) if m else "1.0.0")
PY
    ) || BUILD_VERSION="1.0.0"
fi
echo "  Version : $BUILD_VERSION"

# ── Install PyInstaller if needed ─────────────────────────────────────────────

step "Checking PyInstaller"
if ! python3 -m PyInstaller --version &>/dev/null; then
    echo "  Installing PyInstaller…"
    python3 -m pip install pyinstaller
fi
echo "  PyInstaller: $(python3 -m PyInstaller --version)"

# ── Write PyInstaller spec ────────────────────────────────────────────────────

step "Writing PyInstaller spec"
SPEC_FILE="$SCRIPT_DIR/medtrustx_agent_linux.spec"

cat > "$SPEC_FILE" <<SPEC
# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by build_linux.sh

block_cipher = None
from pathlib import Path

agent_root = Path(r'${AGENT_ROOT}')

a = Analysis(
    [str(agent_root / 'src' / 'main.py')],
    pathex=[str(agent_root)],
    binaries=[],
    datas=[(str(agent_root / '.env.example'), '.')],
    hiddenimports=[
        'src.checks.check_01_os_patch',
        'src.checks.check_02_antivirus',
        'src.checks.check_03_disk_encryption',
        'src.checks.check_04_firewall',
        'src.checks.check_05_screen_lock',
        'src.checks.check_06_jailbreak',
        'src.checks.check_07_certificate',
        'src.checks.check_08_network',
        'src.checks.check_09_processes',
        'src.checks.check_10_behavioral',
        'src.daemon.linux_daemon',
        'src.daemon.macos_daemon',
        'src.daemon.windows_service',
        'src.reporting.zta_reporter',
        'src.reporting.siem_reporter',
        'src.reporting.prometheus_reporter',
        'src.reporting.opa_reporter',
        'cryptography.hazmat.backends.openssl',
        'cryptography.hazmat.primitives.asymmetric.padding',
        'cryptography.x509.ocsp',
        'psycopg2',
        'psycopg2.extensions',
        'aiohttp',
        'aiohttp.web',
        'netifaces',
        'psutil',
        'structlog',
        'click',
        'pydantic',
        'pydantic_settings',
        'sdnotify',
    ],
    hookspath=[],
    runtime_hooks=[],
    excludes=['tkinter', 'matplotlib', 'numpy', 'scipy', 'PIL'],
    cipher=block_cipher,
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)

exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.zipfiles,
    a.datas,
    [],
    name='${EXE_NAME}',
    debug=False,
    strip=True,
    upx=True,
    upx_exclude=[],
    runtime_tmpdir=None,
    console=True,
    target_arch=None,
    codesign_identity=None,
)
SPEC

echo "  Wrote: $SPEC_FILE"

# ── Run PyInstaller ───────────────────────────────────────────────────────────

step "Running PyInstaller"
cd "$AGENT_ROOT"
python3 -m PyInstaller \
    --clean \
    --noconfirm \
    --distpath "$DIST_DIR" \
    --workpath "$WORK_DIR" \
    --log-level WARN \
    "$SPEC_FILE"
chmod +x "$EXE_PATH"
green "PyInstaller build complete: $EXE_PATH"

EXE_SIZE=$(du -sh "$EXE_PATH" | awk '{print $1}')
echo "  Binary size: $EXE_SIZE"

# ── .deb package ──────────────────────────────────────────────────────────────

if [[ "$SKIP_DEB" == "1" ]]; then
    warn "Skipping .deb (SKIP_DEB=1)"
elif ! command -v dpkg-deb &>/dev/null; then
    warn "dpkg-deb not found — skipping .deb packaging"
else
    step "Building .deb package"

    DEB_NAME="medtrustx-agent_${BUILD_VERSION}_${DEB_ARCH}"
    DEB_ROOT="$PKG_WORK_DIR/$DEB_NAME"
    rm -rf "$DEB_ROOT"

    # Create directory tree
    install -d "$DEB_ROOT/DEBIAN"
    install -d "$DEB_ROOT/usr/bin"
    install -d "$DEB_ROOT/etc/medtrustx"
    install -d "$DEB_ROOT/lib/systemd/system"
    install -d "$DEB_ROOT/var/log/medtrustx"

    # Binary
    install -m 755 "$EXE_PATH" "$DEB_ROOT/usr/bin/$EXE_NAME"

    # Default config
    install -m 640 "$AGENT_ROOT/.env.example" "$DEB_ROOT/etc/medtrustx/agent.env"

    # Systemd unit (created in install/linux/ — reference from there if present)
    UNIT_SRC="$AGENT_ROOT/install/linux/medtrustx-agent.service"
    if [[ -f "$UNIT_SRC" ]]; then
        install -m 644 "$UNIT_SRC" "$DEB_ROOT/lib/systemd/system/medtrustx-agent.service"
    fi

    # DEBIAN/control
    cat > "$DEB_ROOT/DEBIAN/control" <<CTRL
Package: medtrustx-agent
Version: ${BUILD_VERSION}
Section: net
Priority: optional
Architecture: ${DEB_ARCH}
Maintainer: MedTrustX <security@medtrustx.io>
Depends: libc6 (>= 2.31)
Description: MedTrustX Device Trust Agent
 Zero Trust endpoint attestation agent for MedTrustX DHOS.
 Runs 10 security checks and reports device posture to the ZTA service.
CTRL

    # DEBIAN/postinst — enable and start the service
    cat > "$DEB_ROOT/DEBIAN/postinst" <<'POSTINST'
#!/bin/sh
set -e
if command -v systemctl >/dev/null 2>&1; then
    systemctl daemon-reload
    systemctl enable medtrustx-agent.service || true
    systemctl start  medtrustx-agent.service || true
fi
POSTINST
    chmod 755 "$DEB_ROOT/DEBIAN/postinst"

    # DEBIAN/prerm — stop the service before removal
    cat > "$DEB_ROOT/DEBIAN/prerm" <<'PRERM'
#!/bin/sh
set -e
if command -v systemctl >/dev/null 2>&1; then
    systemctl stop    medtrustx-agent.service || true
    systemctl disable medtrustx-agent.service || true
fi
PRERM
    chmod 755 "$DEB_ROOT/DEBIAN/prerm"

    DEB_OUT="$DIST_DIR/${DEB_NAME}.deb"
    dpkg-deb --build --root-owner-group "$DEB_ROOT" "$DEB_OUT"
    green "Built .deb: $DEB_OUT ($(du -sh "$DEB_OUT" | awk '{print $1}'))"
fi

# ── .rpm package ──────────────────────────────────────────────────────────────

if [[ "$SKIP_RPM" == "1" ]]; then
    warn "Skipping .rpm (SKIP_RPM=1)"
elif ! command -v rpmbuild &>/dev/null; then
    warn "rpmbuild not found — skipping .rpm packaging"
else
    step "Building .rpm package"

    RPM_BUILD_ROOT="$PKG_WORK_DIR/rpmbuild"
    mkdir -p "$RPM_BUILD_ROOT"/{BUILD,RPMS,SOURCES,SPECS,SRPMS}

    # Pack binary into a tarball for rpmbuild SOURCES
    TAR_NAME="medtrustx-agent-${BUILD_VERSION}"
    TAR_DIR="$PKG_WORK_DIR/$TAR_NAME"
    rm -rf "$TAR_DIR"
    mkdir -p "$TAR_DIR/usr/bin" "$TAR_DIR/etc/medtrustx" "$TAR_DIR/lib/systemd/system"

    cp "$EXE_PATH" "$TAR_DIR/usr/bin/$EXE_NAME"
    cp "$AGENT_ROOT/.env.example" "$TAR_DIR/etc/medtrustx/agent.env"

    UNIT_SRC="$AGENT_ROOT/install/linux/medtrustx-agent.service"
    if [[ -f "$UNIT_SRC" ]]; then
        cp "$UNIT_SRC" "$TAR_DIR/lib/systemd/system/medtrustx-agent.service"
    fi

    tar -czf "$RPM_BUILD_ROOT/SOURCES/${TAR_NAME}.tar.gz" -C "$PKG_WORK_DIR" "$TAR_NAME"

    # Write spec file
    SPEC_RPM="$RPM_BUILD_ROOT/SPECS/medtrustx-agent.spec"
    cat > "$SPEC_RPM" <<RPMSPEC
Name:           medtrustx-agent
Version:        ${BUILD_VERSION}
Release:        1%{?dist}
Summary:        MedTrustX Device Trust Agent
License:        Proprietary
URL:            https://medtrustx.io
Source0:        %{name}-%{version}.tar.gz
BuildArch:      ${RPM_ARCH}
Requires:       glibc >= 2.31

%description
Zero Trust endpoint attestation agent for MedTrustX DHOS.
Runs 10 security checks and reports device posture to the ZTA service.

%prep
%setup -q

%install
install -D -m 755 usr/bin/medtrustx-agent %{buildroot}/usr/bin/medtrustx-agent
install -D -m 640 etc/medtrustx/agent.env  %{buildroot}/etc/medtrustx/agent.env
%if 0%{?_unitdir:1}
install -D -m 644 lib/systemd/system/medtrustx-agent.service \\
    %{buildroot}%{_unitdir}/medtrustx-agent.service
%endif

%files
/usr/bin/medtrustx-agent
%config(noreplace) /etc/medtrustx/agent.env
%{_unitdir}/medtrustx-agent.service

%post
%systemd_post medtrustx-agent.service

%preun
%systemd_preun medtrustx-agent.service

%postun
%systemd_postun_with_restart medtrustx-agent.service

%changelog
* $(date +"%a %b %d %Y") MedTrustX <security@medtrustx.io> - ${BUILD_VERSION}-1
- Initial package
RPMSPEC

    rpmbuild \
        --define "_topdir $RPM_BUILD_ROOT" \
        -bb "$SPEC_RPM"

    RPM_FILE=$(find "$RPM_BUILD_ROOT/RPMS" -name "*.rpm" | head -1)
    if [[ -n "$RPM_FILE" ]]; then
        cp "$RPM_FILE" "$DIST_DIR/"
        RPM_BASENAME=$(basename "$RPM_FILE")
        green "Built .rpm: $DIST_DIR/$RPM_BASENAME ($(du -sh "$DIST_DIR/$RPM_BASENAME" | awk '{print $1}'))"
    else
        warn "rpmbuild ran but no .rpm file was produced"
    fi
fi

# ── Done ──────────────────────────────────────────────────────────────────────

echo
cyan "════════════════════════════════════════════════"
green "Build complete!"
echo "  Output  : $DIST_DIR/"
ls -lh "$DIST_DIR/" 2>/dev/null || true
echo "  Version : $BUILD_VERSION"
echo "  Arch    : $TARGET_ARCH"
cyan "════════════════════════════════════════════════"
