<#
.SYNOPSIS
    MedTrustX Device Trust Agent — Windows Build Script

.DESCRIPTION
    Builds a self-contained Windows executable using PyInstaller,
    then optionally code-signs it with signtool.exe.

    Prerequisites:
      - Python 3.11+ in PATH
      - pip install pyinstaller (included in requirements-dev.txt)
      - signtool.exe (Windows SDK) in PATH for signing
      - A code-signing certificate in the Windows Certificate Store
        OR a PFX file path set in $env:SIGN_PFX_PATH

    Output:
      dist\medtrustx-agent.exe   — signed, single-file executable

    Environment variables (all optional):
      SIGN_PFX_PATH        — path to PFX certificate file
      SIGN_PFX_PASSWORD    — PFX file password
      SIGN_CERT_THUMBPRINT — thumbprint for store-based signing
      SIGN_TIMESTAMP_URL   — TSA URL (default: http://timestamp.digicert.com)
      BUILD_VERSION        — version string embedded in exe (default: from pyproject.toml)
      DIST_DIR             — output directory (default: dist)
      WORK_DIR             — PyInstaller work dir (default: build\pyinstaller_work)
#>

[CmdletBinding()]
param(
    [switch]$SkipSign,
    [switch]$Clean,
    [switch]$Verbose
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

# ── Configuration ────────────────────────────────────────────────────────────

$ScriptDir   = Split-Path -Parent $MyInvocation.MyCommand.Path
$AgentRoot   = Split-Path -Parent $ScriptDir
$DistDir     = if ($env:DIST_DIR)   { $env:DIST_DIR   } else { Join-Path $AgentRoot "dist" }
$WorkDir     = if ($env:WORK_DIR)   { $env:WORK_DIR   } else { Join-Path $ScriptDir "pyinstaller_work" }
$SpecFile    = Join-Path $ScriptDir "medtrustx_agent.spec"
$ExeName     = "medtrustx-agent.exe"
$ExePath     = Join-Path $DistDir $ExeName
$TimestampUrl = if ($env:SIGN_TIMESTAMP_URL) { $env:SIGN_TIMESTAMP_URL } else { "http://timestamp.digicert.com" }

# ── Helpers ──────────────────────────────────────────────────────────────────

function Write-Step([string]$msg) {
    Write-Host "`n[MedTrustX Build] $msg" -ForegroundColor Cyan
}

function Write-Success([string]$msg) {
    Write-Host "[OK] $msg" -ForegroundColor Green
}

function Write-Fail([string]$msg) {
    Write-Host "[FAIL] $msg" -ForegroundColor Red
    exit 1
}

function Invoke-Cmd([string]$cmd, [string[]]$args) {
    if ($Verbose) {
        Write-Host "  > $cmd $($args -join ' ')" -ForegroundColor DarkGray
    }
    & $cmd @args
    if ($LASTEXITCODE -ne 0) {
        Write-Fail "Command failed (exit $LASTEXITCODE): $cmd $($args -join ' ')"
    }
}

# ── Clean ────────────────────────────────────────────────────────────────────

if ($Clean) {
    Write-Step "Cleaning previous build artefacts"
    foreach ($dir in @($DistDir, $WorkDir)) {
        if (Test-Path $dir) {
            Remove-Item -Recurse -Force $dir
            Write-Host "  Removed: $dir"
        }
    }
}

# ── Verify Python ─────────────────────────────────────────────────────────────

Write-Step "Verifying Python environment"
$PythonVersion = & python --version 2>&1
Write-Host "  Python: $PythonVersion"
if ($PythonVersion -notmatch "Python 3\.(1[1-9]|[2-9]\d)") {
    Write-Fail "Python 3.11+ required. Found: $PythonVersion"
}

# ── Install / verify PyInstaller ──────────────────────────────────────────────

Write-Step "Checking PyInstaller"
$PyInstallerVersion = & python -m PyInstaller --version 2>&1
if ($LASTEXITCODE -ne 0) {
    Write-Host "  PyInstaller not found — installing from requirements-dev.txt"
    Invoke-Cmd python @("-m", "pip", "install", "pyinstaller")
}
Write-Host "  PyInstaller: $($PyInstallerVersion | Select-Object -First 1)"

# ── Generate PyInstaller spec (if not present) ────────────────────────────────

Write-Step "Preparing PyInstaller spec"

if (-not (Test-Path $SpecFile)) {
    $SpecContent = @"
# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by build_windows.ps1 — do not edit manually.

import sys
from pathlib import Path

block_cipher = None
agent_root = Path(SPECPATH).parent

a = Analysis(
    [str(agent_root / 'src' / 'main.py')],
    pathex=[str(agent_root)],
    binaries=[],
    datas=[
        (str(agent_root / '.env.example'), '.'),
    ],
    hiddenimports=[
        # Checks
        'src.checks.check_01_os_patch',
        'src.checks.check_02_antivirus',
        'src.checks.check_03_disk_encryption',
        'src.checks.check_04_firewall',
        'src.checks.check_05_screen_lock',
        'src.checks.check_06_jailbreak',
        'src.checks.check_07_certificate',
        'src.checks.check_08_network',
        'src.checks.check_09_processes',
        'src.checks.check_10_behavioral',
        # Platform daemons
        'src.daemon.linux_daemon',
        'src.daemon.macos_daemon',
        'src.daemon.windows_service',
        # Reporters
        'src.reporting.zta_reporter',
        'src.reporting.siem_reporter',
        'src.reporting.prometheus_reporter',
        'src.reporting.opa_reporter',
        # Windows-specific
        'win32serviceutil',
        'win32service',
        'win32event',
        'pywintypes',
        'winerror',
        # Crypto / network
        'cryptography.hazmat.backends.openssl',
        'cryptography.hazmat.primitives.asymmetric.padding',
        'cryptography.x509.ocsp',
        'psycopg2',
        'psycopg2.extensions',
        'aiohttp',
        'aiohttp.web',
        'netifaces',
        'psutil',
        'structlog',
        'click',
        'pydantic',
        'pydantic_settings',
    ],
    hookspath=[],
    hooksconfig={},
    runtime_hooks=[],
    excludes=['tkinter', 'matplotlib', 'numpy', 'scipy', 'PIL'],
    win_no_prefer_redirects=False,
    win_private_assemblies=False,
    cipher=block_cipher,
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)

exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.zipfiles,
    a.datas,
    [],
    name='medtrustx-agent',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=True,
    upx_exclude=[],
    runtime_tmpdir=None,
    console=True,
    disable_windowed_traceback=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
    version=str(agent_root / 'build' / 'version_info.txt'),
    icon=None,
)
"@
    Set-Content -Path $SpecFile -Value $SpecContent -Encoding UTF8
    Write-Host "  Wrote spec: $SpecFile"
} else {
    Write-Host "  Using existing spec: $SpecFile"
}

# ── Write Windows version info resource ───────────────────────────────────────

$BuildVersion = if ($env:BUILD_VERSION) { $env:BUILD_VERSION } else { "1.0.0.0" }
$VersionTuple = ($BuildVersion -replace "[^0-9.]", "") -split "\." | ForEach-Object { [int]$_ }
while ($VersionTuple.Count -lt 4) { $VersionTuple += @(0) }
$VInfo = @"
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=($($VersionTuple[0]), $($VersionTuple[1]), $($VersionTuple[2]), $($VersionTuple[3])),
    prodvers=($($VersionTuple[0]), $($VersionTuple[1]), $($VersionTuple[2]), $($VersionTuple[3])),
    mask=0x3f,
    flags=0x0,
    OS=0x4,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [StringStruct('CompanyName', 'MedTrustX'),
         StringStruct('FileDescription', 'MedTrustX Device Trust Agent'),
         StringStruct('FileVersion', '$BuildVersion'),
         StringStruct('InternalName', 'medtrustx-agent'),
         StringStruct('LegalCopyright', 'Copyright (C) 2024 MedTrustX'),
         StringStruct('OriginalFilename', 'medtrustx-agent.exe'),
         StringStruct('ProductName', 'MedTrustX Device Trust Agent'),
         StringStruct('ProductVersion', '$BuildVersion')])
    ]),
    VarFileInfo([VarStruct('Translation', [0x0409, 0x04B0])])
  ]
)
"@
$VersionFile = Join-Path $ScriptDir "version_info.txt"
Set-Content -Path $VersionFile -Value $VInfo -Encoding UTF8

# ── Run PyInstaller ───────────────────────────────────────────────────────────

Write-Step "Running PyInstaller"
Push-Location $AgentRoot
try {
    Invoke-Cmd python @(
        "-m", "PyInstaller",
        "--clean",
        "--noconfirm",
        "--distpath", $DistDir,
        "--workpath", $WorkDir,
        "--log-level", $(if ($Verbose) { "DEBUG" } else { "WARN" }),
        $SpecFile
    )
} finally {
    Pop-Location
}
Write-Success "PyInstaller build complete: $ExePath"

# ── Code signing ──────────────────────────────────────────────────────────────

if (-not $SkipSign) {
    Write-Step "Code-signing executable"

    $SignTool = Get-Command signtool.exe -ErrorAction SilentlyContinue
    if (-not $SignTool) {
        Write-Host "  signtool.exe not found — skipping signing" -ForegroundColor Yellow
    } else {
        $SignArgs = @("sign", "/fd", "SHA256", "/tr", $TimestampUrl, "/td", "SHA256")

        if ($env:SIGN_CERT_THUMBPRINT) {
            $SignArgs += @("/sha1", $env:SIGN_CERT_THUMBPRINT)
        } elseif ($env:SIGN_PFX_PATH) {
            $SignArgs += @("/f", $env:SIGN_PFX_PATH)
            if ($env:SIGN_PFX_PASSWORD) {
                $SignArgs += @("/p", $env:SIGN_PFX_PASSWORD)
            }
        } else {
            Write-Host "  No signing cert configured (SIGN_CERT_THUMBPRINT / SIGN_PFX_PATH)" -ForegroundColor Yellow
            Write-Host "  Skipping signing." -ForegroundColor Yellow
            goto SignDone
        }

        $SignArgs += $ExePath
        Invoke-Cmd $SignTool.Source $SignArgs
        Write-Success "Signed: $ExePath"

        # Verify signature
        Invoke-Cmd $SignTool.Source @("verify", "/pa", "/v", $ExePath)
        Write-Success "Signature verified"
    }
}

:SignDone

# ── Done ──────────────────────────────────────────────────────────────────────

$ExeSize = [math]::Round((Get-Item $ExePath).Length / 1MB, 1)
Write-Host ""
Write-Host "════════════════════════════════════════════════" -ForegroundColor Cyan
Write-Host "  Build complete!" -ForegroundColor Green
Write-Host "  Output : $ExePath"
Write-Host "  Size   : ${ExeSize} MB"
Write-Host "  Version: $BuildVersion"
Write-Host "════════════════════════════════════════════════" -ForegroundColor Cyan
